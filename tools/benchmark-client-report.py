#!/usr/bin/env python3
"""Turns the RESULT lines of the Kotlin client benchmark into a table: medians over all rounds, with their ranges."""
import collections
import statistics
import sys

scores = collections.defaultdict(list)
binary = None
for line in open(sys.argv[1]):
    parts = line.split()
    if parts[0] != "RESULT":
        continue
    if parts[1] == "size":
        binary = int(parts[4])
        continue
    platform, transport, sslmode, name, *values = parts[1:]
    scores[platform, transport, sslmode, name] += [float(v) for v in values]

columns = [("native", "epoll", "Native, epoll"), ("native", "ktor", "Native, ktor"), ("jvm", "ktor", "JVM, ktor"), ("jvm", "async", "JVM, AsyncSocketTransport")]


def number(v):
    return f"{v:,.1f}" if v < 100 else f"{v:,.0f}"


def cell(platform, transport, sslmode, name):
    values = scores.get((platform, transport, sslmode, name))
    if not values:
        return "–"
    if len(values) == 1:
        return number(values[0])
    return f"{number(statistics.median(values))} ({number(min(values))}–{number(max(values))})"


def table(sslmode, names):
    rows = ["| Scenario | " + " | ".join(c[2] for c in columns) + " |", "|---|" + "---:|" * len(columns)]
    for name in names:
        rows.append(f"| {name} | " + " | ".join(cell(p, t, sslmode, name) for p, t, _ in columns) + " |")
    return rows


names = ["connect", "connectPerQuery", "connectPerQuery8", "selectOne", "selectOne8", "selectOne32", "pool8on8", "pool32on8", "select1000Rows", "streamAllRows", "insertOne", "insertBatch1000", "copyIn1000", "copyInRaw1000", "transaction"]
present = [n for n in names if any(k[3] == n and k[2] == "disable" for k in scores)]
lines = ["# Kotlin client: JVM and native", "", "Generated by `tools/run-client-benchmarks.sh`, with the same code on each. Client and server in Docker on one machine.", "",
         "## Without TLS, operations per second (higher is better)", "", "Median over all iterations, slowest and fastest in parentheses.", ""]
lines += table("disable", present)
lines += ["", "## With TLS (`sslmode=require`), operations per second", ""]
lines += table("require", [n for n in present if any(k[3] == n and k[2] == "require" for k in scores)])
lines += ["", "## Process", ""] + table("disable", ["firstQueryMillis", "peakRssKb"])
if binary:
    lines += ["", f"The native binary is {binary / 1024 / 1024:.1f} MB, with OpenSSL linked statically and no JVM needed."]
text = "\n".join(lines) + "\n"
open(sys.argv[2], "w").write(text)
print(text)
