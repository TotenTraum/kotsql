import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.*;

/**
 * Generates ksql-jdbc's JdbcBases.kt: base classes that implement every abstract method of the big java.sql interfaces,
 * so the real classes override only what they support. Run: java tools/GenerateJdbcBases.java > .../JdbcBases.kt
 */
public class GenerateJdbcBases {
    static String type(Class<?> c) {
        if (c == int.class) return "Int"; if (c == long.class) return "Long"; if (c == boolean.class) return "Boolean";
        if (c == short.class) return "Short"; if (c == byte.class) return "Byte"; if (c == float.class) return "Float";
        if (c == double.class) return "Double"; if (c == void.class) return "Unit";
        if (c == byte[].class) return "ByteArray"; if (c == int[].class) return "IntArray"; if (c == long[].class) return "LongArray";
        if (c.isArray()) return "Array<" + (c == Object[].class ? "out Any" : "out " + type(c.getComponentType()).replace("?", "")) + ">";
        if (c == Object.class) return "Any";
        if (c == String.class) return "String";
        if (c == Class.class) return "Class<*>";
        if (c == Map.class) return "MutableMap<String, Class<*>>";
        if (c == Properties.class) return "java.util.Properties";
        return c.getCanonicalName();
    }
    static String defaultValue(Class<?> r, String name) {
        if (r == void.class) return "Unit"; if (r == boolean.class) return "false";
        if (r == int.class) return "0"; if (r == long.class) return "0L";
        if (r == String.class) return "\"\"";
        if (r == java.sql.ResultSet.class) return "emptyMetadata(\"" + name + "\")";
        return null;
    }
    static void emit(StringBuilder sb, Class<?> iface, String cls, boolean metadataDefaults, Set<Class<?>> skipFrom) {
        sb.append("abstract class ").append(cls).append(" : ").append(iface.getCanonicalName()).append(" {\n");
        List<Method> ms = new ArrayList<>(List.of(iface.getMethods()));
        ms.sort(Comparator.comparing(Method::getName).thenComparing(m -> Arrays.toString(m.getParameterTypes())));
        Set<String> seen = new HashSet<>();
        for (Method m : ms) {
            if (!Modifier.isAbstract(m.getModifiers())) continue;
            String sig = m.getName() + Arrays.toString(m.getParameterTypes());
            if (!seen.add(sig)) continue;
            StringBuilder ps = new StringBuilder();
            int i = 0;
            for (Class<?> p : m.getParameterTypes()) {
                if (i > 0) ps.append(", ");
                String t = type(p);
                ps.append("p").append(i++).append(": ").append(t).append(p.isPrimitive() ? "" : "?");
            }
            Class<?> r = m.getReturnType();
            String rt = type(r) + (r.isPrimitive() ? "" : "?");
            String tp = "";
            if (m.getTypeParameters().length > 0) { tp = "<T> "; if (r == Object.class) rt = "T"; ps = new StringBuilder(ps.toString().replace("Class<*>?", "Class<T>?")); }
            String body = metadataDefaults ? defaultValue(r, m.getName()) : null;
            if (body == null) body = "unsupported(\"" + m.getName() + "\")";
            sb.append("    override fun ").append(tp).append(m.getName()).append("(").append(ps).append("): ").append(rt).append(" = ").append(body).append("\n");
        }
        sb.append("}\n\n");
    }
    public static void main(String[] a) {
        StringBuilder sb = new StringBuilder("// Generated by tools/GenerateJdbcBases.java. Do not edit.\n@file:Suppress(\"PLATFORM_CLASS_MAPPED_TO_KOTLIN\", \"DEPRECATION\", \"OVERRIDE_DEPRECATION\")\n\npackage dev.ksql.jdbc\n\n");
        emit(sb, java.sql.ResultSet.class, "BaseResultSet", false, null);
        emit(sb, java.sql.PreparedStatement.class, "BasePreparedStatement", false, null);
        emit(sb, java.sql.Connection.class, "BaseConnection", false, null);
        emit(sb, java.sql.DatabaseMetaData.class, "BaseDatabaseMetaData", true, null);
        System.out.print(sb);
    }
}
