#!/usr/bin/env python3
"""Turns JMH's results.json into RESULTS.md: one row per scenario, one column per driver.

Reports the median over all iterations and their range, rather than JMH's mean and error: where the machine is shared, as
in a Docker VM on a laptop, single iterations can be several times slower for reasons outside the benchmark, for any driver.
"""
import json
import pathlib
import statistics
import sys

out = pathlib.Path(sys.argv[1])
results = json.loads((out / "results.json").read_text())
scores = {}
order = []
for r in results:
    cls, name = r["benchmark"].rsplit(".", 2)[-2:]
    params = r.get("params", {})
    if cls == "JdbcBenchmark":
        driver = {"pgjdbc": "pgjdbc", "kotsql": "kotsql-jdbc"}[params["driver"]]
    else:
        driver = {"kotsql": "kotsql-r2dbc", "postgresql": "r2dbc-postgresql"}[params.get("driver", "kotsql")]
    key = (name, params.get("sslmode", "disable"))
    if key not in order:
        order.append(key)
    alloc = r["secondaryMetrics"].get("·gc.alloc.rate.norm") or r["secondaryMetrics"].get("gc.alloc.rate.norm")
    iterations = [x for fork in r["primaryMetric"]["rawData"] for x in fork]
    scores[key, driver] = (statistics.median(iterations), (min(iterations), max(iterations)), alloc["score"] if alloc else None)


def number(v):
    return f"{v:,.1f}" if v < 100 else f"{v:,.0f}"


def ratio(key, driver, base="pgjdbc"):
    if (key, driver) not in scores or (key, base) not in scores:
        return "–"
    return f"{scores[key, driver][0] / scores[key, base][0]:.2f}×"


def cell(key, driver):
    if (key, driver) not in scores:
        return "–"
    score, (low, high), _ = scores[key, driver]
    return f"{number(score)} ({number(low)}–{number(high)})"


def alloc(key, driver):
    if (key, driver) not in scores or scores[key, driver][2] is None:
        return "–"
    return f"{scores[key, driver][2] / 1024:,.1f}"


def label(key):
    return key[0] if key[1] == "disable" else f"{key[0]} (sslmode={key[1]})"


lines = [
    "# Benchmark results",
    "",
    f"Generated by `tools/run-benchmarks.sh`. PostgreSQL {(out / 'server-version.txt').read_text().strip()}, client and server in Docker on one machine.",
    "",
    "## Throughput, operations per second (higher is better)",
    "",
    "Median over all iterations, with the slowest and the fastest in parentheses. Ratios compare medians.",
    "",
    "| Scenario | pgjdbc | kotsql-jdbc | kotsql-jdbc / pgjdbc | kotsql-r2dbc | r2dbc-postgresql | kotsql-r2dbc / r2dbc-postgresql |",
    "|---|---:|---:|---:|---:|---:|---:|",
]
for key in order:
    lines.append(f"| {label(key)} | {cell(key, 'pgjdbc')} | {cell(key, 'kotsql-jdbc')} | {ratio(key, 'kotsql-jdbc')} | {cell(key, 'kotsql-r2dbc')} | {cell(key, 'r2dbc-postgresql')} | {ratio(key, 'kotsql-r2dbc', 'r2dbc-postgresql')} |")
lines += [
    "",
    "## Allocation, KB per operation (lower is better)",
    "",
    "| Scenario | pgjdbc | kotsql-jdbc | kotsql-r2dbc | r2dbc-postgresql |",
    "|---|---:|---:|---:|---:|",
]
for key in order:
    lines.append(f"| {label(key)} | {alloc(key, 'pgjdbc')} | {alloc(key, 'kotsql-jdbc')} | {alloc(key, 'kotsql-r2dbc')} | {alloc(key, 'r2dbc-postgresql')} |")
(out / "RESULTS.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
