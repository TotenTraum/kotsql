    override fun getIdentifier(index: Int) = getPlaceholder(index)
    override fun getCreateTableWithAutogeneratedKey() = "CREATE TABLE test (id SERIAL PRIMARY KEY, test_value INTEGER)"
    override fun blobType() = "BYTEA"
