class R2dbcTest {
    private fun <T : Any> withConnection(block: (Connection) -> Mono<T>): T? =
        Mono.usingWhen(Mono.from(Pg.factory.create()), block) { Mono.from(it.close()) }.block(Pg.timeout)

    private fun rows(c: Connection, sql: String): Flux<Any> =
        Flux.from(c.createStatement(sql).execute()).concatMap { r -> r.map { row, _ -> row.get(0)!! } }

    @Test fun commonIdiomMonoFromExecuteStillReadsTheRows() {
        val values = withConnection { c ->
            // Mono.from cancels the statement publisher as soon as the Result arrives.
            Mono.from(c.createStatement("SELECT generate_series(1, 5)").execute())
                .flatMapMany { r -> r.map { row, _ -> row.get(0, Integer::class.java)!!.toInt() } }
                .collectList()
        }
        assertEquals(listOf(1, 2, 3, 4, 5), values)
    }

    @Test fun resultsCollectedFirstAndReadLater() {
        val values = withConnection { c ->
            Flux.from(c.createStatement("SELECT 1; SELECT 2").execute()).collectList()
                .flatMapMany { results -> Flux.fromIterable(results).concatMap { r -> r.map { row, _ -> row.get(0) as Any } } }
                .collectList()
        }
        assertEquals(listOf<Any>(1, 2), values)
    }

    @Test fun honoursBackpressureAndCancellation() {
        val taken = withConnection { c ->
            Flux.from(c.createStatement("SELECT generate_series(1, 20000000)").fetchSize(100).execute())
                .concatMap { r -> r.map { row, _ -> row.get(0) as Int } }
                .take(5)
                .collectList()
                // The connection is usable right away. Were the unread rows being fetched, this would time out.
                .flatMap { first -> rows(c, "SELECT 42").collectList().map { first + it } }
        }
        assertEquals(listOf<Any>(1, 2, 3, 4, 5, 42), taken)
    }

    @Test fun rowsStayOnTheServerUntilRequested() {
        // 20M rows would take far longer than the timeout to fetch, and would not fit in the test JVM's heap.
        val first = withConnection { c ->
            Flux.from(c.createStatement("SELECT generate_series(1, 20000000)").fetchSize(50).execute())
                .concatMap { r -> r.map { row, _ -> row.get(0) as Int } }
                .limitRate(1)
                .take(1)
                .next()
        }
        assertEquals(1, first)
    }

    @Test fun laterSubscriberStillGetsARowsResultAfterCancellation() {
        val result = Mono.from(Pg.factory.create()).flatMap { c -> Mono.from(c.createStatement("SELECT generate_series(1, 3)").execute()) }.block(Pg.timeout)!!
        // Subscribing long after Mono.from cancelled the statement publisher.
        Thread.sleep(100)
        val rows = Flux.from(result.map { row, _ -> row.get(0) as Int }).collectList().block(Pg.timeout)
        assertEquals(listOf(1, 2, 3), rows)
    }

    @Test fun resultCanBeConsumedOnlyOnce() {
        withConnection<Int> { c ->
            Mono.from(c.createStatement("SELECT 1").execute()).flatMap { r ->
                Flux.from(r.map { row, _ -> row.get(0) as Int }).collectList().then(
                    Flux.from(r.map { row, _ -> row.get(0) as Int }).collectList()
                        .map<Int> { error("a second consumer got $it") }
                        .onErrorResume(IllegalStateException::class.java) { e ->
                            assertTrue("once" in e.message!!, e.toString())
                            Mono.just(1)
                        },
                )
            }
        }
    }

    @Test fun limitRateDoesNotLoseRows() {
        val sum = withConnection { c ->
            Flux.from(c.createStatement("SELECT generate_series(1, 20000)").execute())
                .concatMap { r -> r.map { row, _ -> (row.get(0) as Int).toLong() } }
                .limitRate(16)
                .reduce(0L, Long::plus)
        }
        assertEquals(200010000L, sum)
    }

    @Test fun bindsTypesAndGeneratedValues() {
        val id = UUID.randomUUID()
        val row = withConnection<List<Any?>> { c ->
            Mono.from(c.createStatement("CREATE TEMP TABLE b(id serial, u uuid, d date, n numeric)").execute()).flatMap { Mono.from(it.rowsUpdated).defaultIfEmpty(0L) }
                .then(
                    Mono.from(
                        c.createStatement("INSERT INTO b(u, d, n) VALUES ($1, $2, $3)")
                            .bind("$1", id).bind(1, LocalDate.of(2024, 2, 29)).bindNull(2, java.math.BigDecimal::class.java)
                            .returnGeneratedValues("id", "u").execute(),
                    ),
                ).flatMap { r: Result -> Mono.from(r.map { row, _ -> listOf<Any?>(row.get("id", Integer::class.java)!!.toInt(), row.get("u", UUID::class.java)) }) }
        }
        assertEquals(listOf<Any?>(1, id), row)
    }

    @Test fun mapsErrors() {
        withConnection<Int> { c ->
            rows(c, "SELEC").then(Mono.just(1)).onErrorResume { e: Throwable -> assertTrue(e is R2dbcBadGrammarException && e.sqlState == "42601", e.toString()); Mono.just(1) }
        }
        val e = assertFailsWith<R2dbcDataIntegrityViolationException> {
            withConnection<Int> { c ->
                Flux.from(c.createStatement("CREATE TEMP TABLE e(a int PRIMARY KEY); INSERT INTO e VALUES (1); INSERT INTO e VALUES (1)").execute())
                    .concatMap { it.rowsUpdated }.then(Mono.just(1))
            }
        }
        assertEquals("23505", e.sqlState)
        assertEquals(ru.ttraum.kotsql.ConstraintViolation.UNIQUE, e.sqlErrorDetails()?.violation); assertEquals("e_pkey", e.sqlErrorDetails()?.constraint)
    }

    @Test fun tls() {
        fun viaUrl(query: String) = ConnectionFactories.get("r2dbc:kotsql:postgresql://${Pg.base}?$query")
        fun ssl(f: ConnectionFactory) = Mono.usingWhen(Mono.from(f.create()), { c ->
            rows(c, "SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()").next()
        }) { Mono.from(it.close()) }.block(Pg.timeout)
        assertEquals(false, ssl(viaUrl("sslmode=disable")))
        assertEquals(true, ssl(viaUrl("sslmode=require")))
        // The self-signed certificate must be refused when verification is on.
        assertFailsWith<R2dbcException> { ssl(viaUrl("sslmode=verify-ca")) }

        val cert = java.nio.file.Files.createTempFile("pg", ".pem").toFile()
        Pg.container.copyFileFromContainer("/etc/ssl/certs/ssl-cert-snakeoil.pem", cert.path)
        val port = Pg.container.firstMappedPort
        val auth = "${Pg.container.username}:${Pg.container.password}"
        val db = Pg.container.databaseName
        val pinned = "sslrootcert=${cert.path}"
        assertEquals(true, ssl(ConnectionFactories.get("r2dbc:kotsql:postgresql://$auth@127.0.0.1:$port/$db?sslmode=verify-ca&$pinned")))
        assertEquals(true, ssl(ConnectionFactories.get("r2dbc:kotsql:postgresql://$auth@localhost:$port/$db?sslmode=verify-full&$pinned")))
        assertFailsWith<R2dbcException> { ssl(ConnectionFactories.get("r2dbc:kotsql:postgresql://$auth@127.0.0.1:$port/$db?sslmode=verify-full&$pinned")) }
    }

    @Test fun tlsCarriesLargeDataAndUsesCurrentProtocol() {
        val secure = ConnectionFactories.get("r2dbc:kotsql:postgresql://${Pg.base}?sslmode=require")
        val big = "дата-😀-".repeat(200_000)
        val result = Mono.usingWhen(Mono.from(secure.create()), { c ->
            val echo = Flux.from(c.createStatement("SELECT $1::text").bind(0, big).execute())
                .concatMap { r -> r.map { row, _ -> row.get(0, String::class.java)!! } }.next()
            val sum = rows(c, "SELECT generate_series(1, 300000)").map { (it as Int).toLong() }.reduce(0L, Long::plus)
            val version = rows(c, "SELECT version FROM pg_stat_ssl WHERE pid = pg_backend_pid()").next()
            Mono.zip(echo, sum, version).map { listOf(it.t1 == big, it.t2, it.t3) }
        }) { Mono.from(it.close()) }.block(Duration.ofSeconds(60))
        assertEquals(listOf<Any>(true, 45000150000L, "TLSv1.3"), result)
    }

    @Test fun connectionFailuresAreReported() {
        fun failure(url: String) = assertFailsWith<R2dbcException> { Mono.from(ConnectionFactories.get(url).create()).block(Pg.timeout) }
        val auth = "${Pg.container.username}:${Pg.container.password}"
        // A port with nothing listening: this one was just free.
        val freePort = java.net.ServerSocket(0).use { it.localPort }
        assertEquals("08001", failure("r2dbc:kotsql:postgresql://$auth@localhost:$freePort/x?sslmode=disable").sqlState)
        assertEquals("08001", failure("r2dbc:kotsql:postgresql://$auth@no-such-host.invalid:5432/x?sslmode=disable").sqlState)
        assertEquals("28P01", failure("r2dbc:kotsql:postgresql://$auth-wrong@${Pg.container.host}:${Pg.container.firstMappedPort}/${Pg.container.databaseName}?sslmode=disable").sqlState)
    }

    @Test fun callbacksNeedNotWaitForEachOtherAcrossConnections() {
        // Two connections on separate event threads, with a callback of one waiting for a query on the other.
        val done = Mono.usingWhen(Mono.from(Pg.factory.create()), { a ->
            Mono.usingWhen(Mono.from(Pg.factory.create()), { b ->
                rows(a, "SELECT 1").publishOn(reactor.core.scheduler.Schedulers.boundedElastic())
                    .map { rows(b, "SELECT 2").blockFirst() as Int }
                    .next()
            }) { Mono.from(it.close()) }
        }) { Mono.from(it.close()) }.block(Pg.timeout)
        assertEquals(2, done)
    }

    @Test fun codecs() {
        val options = io.r2dbc.spi.ConnectionFactoryOptions.parse("r2dbc:kotsql:postgresql://${Pg.base}").mutate()
            .option(io.r2dbc.spi.Option.valueOf("codecs"), ru.ttraum.kotsql.CodecRegistry(ru.ttraum.kotsql.SqlCodec.enum<R2Mood>("r2_mood"))).build()
        val factory = ConnectionFactories.get(options)
        val row = Mono.usingWhen(Mono.from(factory.create()), { c ->
            rows(c, "DROP TYPE IF EXISTS r2_mood CASCADE").then().then(rows(c, "CREATE TYPE r2_mood AS ENUM ('SAD', 'HAPPY')").then())
                .then(
                    Flux.from(c.createStatement("SELECT $1::r2_mood, 'SAD'::text").bind(0, R2Mood.HAPPY).execute())
                        .concatMap { r -> r.map { row, _ -> listOf(row.get(0), row.get(0, R2Mood::class.java), row.get(1, R2Mood::class.java)) } }
                        .next(),
                )
        }) { Mono.from(it.close()) }.block(Pg.timeout)
        assertEquals(listOf<Any?>(R2Mood.HAPPY, R2Mood.HAPPY, R2Mood.SAD), row)
    }

    @Test fun connectionPoolUnderLoad() {
        val pool = ConnectionPool(ConnectionPoolConfiguration.builder(Pg.factory).maxSize(4).initialSize(1).validationQuery("SELECT 1").build())
        val sum = Flux.range(1, 300).flatMap({ i ->
            Mono.usingWhen(pool.create(), { c -> rows(c, "SELECT $i").next().map { it as Int } }) { Mono.from(it.close()) }
        }, 32).reduce(0, Int::plus).block(Pg.timeout)
        assertEquals(45150, sum)
        pool.dispose()
    }

    @Test fun springDatabaseClient() {
        val client = DatabaseClient.create(Pg.factory)
        client.sql("DROP TABLE IF EXISTS sp").then().block(Pg.timeout)
        client.sql("CREATE TABLE sp(id serial PRIMARY KEY, name text)").then().block(Pg.timeout)
        val inserted = client.sql("INSERT INTO sp(name) VALUES (:name)").bind("name", "ada").fetch().rowsUpdated().block(Pg.timeout)
        assertEquals(1L, inserted)
        val name = client.sql("SELECT name FROM sp WHERE name = :name").bind("name", "ada").map { row, _ -> row.get("name", String::class.java)!! }.one().block(Pg.timeout)
        assertEquals("ada", name)
    }
}

internal object My {
    const val DATABASE = "test"
    const val USER = "test"
    const val PASSWORD = "test"

    val container: org.testcontainers.containers.GenericContainer<Nothing> by lazy {
        org.testcontainers.containers.GenericContainer<Nothing>("mysql:8.4").apply {
            withEnv("MYSQL_ROOT_PASSWORD", PASSWORD)
            withEnv("MYSQL_DATABASE", DATABASE)
            withEnv("MYSQL_USER", USER)
            withEnv("MYSQL_PASSWORD", PASSWORD)
            withExposedPorts(3306)
            waitingFor(org.testcontainers.containers.wait.strategy.Wait.forLogMessage(".*ready for connections.*port: 3306.*", 1).withStartupTimeout(Duration.ofMinutes(3)))
            start()
        }
    }
    val hostPort get() = "${container.host}:${container.firstMappedPort}"
    val factory: ConnectionFactory by lazy { ConnectionFactories.get("r2dbc:kotsql:mysql://$USER:$PASSWORD@$hostPort/$DATABASE") }
}

/** The official R2DBC compatibility kit, on an adapter that knows nothing of MySQL. */
class MysqlR2dbcTckTest : TestKit<String> {
    override fun getConnectionFactory() = My.factory
    override fun getPlaceholder(index: Int) = "?"
    override fun getIdentifier(index: Int) = "?${index + 1}"
    override fun getCreateTableWithAutogeneratedKey() = "CREATE TABLE test (id INT AUTO_INCREMENT PRIMARY KEY, test_value INT)"

    /** The kit's default leaves a column out with VALUES(100), which PostgreSQL allows and MySQL doesn't. */
    override fun getInsertIntoWithAutogeneratedKey() = "INSERT INTO test (test_value) VALUES (100)"
    override fun blobType() = "BLOB"
    override fun clobType() = "TEXT"
    override fun getJdbcOperations(): JdbcOperations = JdbcTemplate(
        KotsqlDataSource("jdbc:kotsql:mysql://${My.hostPort}/${My.DATABASE}", My.USER, My.PASSWORD),
    )
}

class MysqlR2dbcTest {
    private fun <T : Any> withConnection(block: (Connection) -> Mono<T>): T? =
        Mono.usingWhen(Mono.from(My.factory.create()), block) { Mono.from(it.close()) }.block(Pg.timeout)

    @Test fun streamsAndBinds() {
        val values = withConnection<List<Long>> { c ->
            Flux.from(c.createStatement("SELECT ? + 1").bind(0, 41L).execute())
                .concatMap { r -> r.map { row, _ -> row.get(0, java.lang.Long::class.java)!!.toLong() } }
                .collectList()
        }
        assertEquals(listOf(42L), values)
    }

    @Test fun generatedValues() {
        val key = withConnection<Long> { c ->
            Mono.from(c.createStatement("CREATE TEMPORARY TABLE g(id INT AUTO_INCREMENT PRIMARY KEY, v INT)").execute()).flatMap { Mono.from(it.rowsUpdated).defaultIfEmpty(0L) }
                .then(Mono.from(c.createStatement("INSERT INTO g(v) VALUES (?)").bind(0, 1).returnGeneratedValues("id").execute()))
                .flatMap { r: Result -> Mono.from(r.map { row, _ -> row.get(0, java.lang.Long::class.java)!!.toLong() }) }
        }
        assertEquals(1L, key)
    }

    @Test fun paging() {
        val sum = withConnection<Long> { c ->
            Flux.from(c.createStatement("SELECT a.n * 10 + b.n FROM (SELECT 0 n UNION SELECT 1 UNION SELECT 2) a, (SELECT 0 n UNION SELECT 1 UNION SELECT 2 UNION SELECT 3) b").fetchSize(5).execute())
                .concatMap { r -> r.map { row, _ -> row.get(0, java.lang.Long::class.java)!!.toLong() } }
                .reduce(0L, Long::plus)
        }
        assertEquals(138L, sum)
    }

    @Test fun mapsErrors() {
        val e = assertFailsWith<R2dbcBadGrammarException> {
            withConnection<Int> { c -> Flux.from(c.createStatement("SELEC").execute()).then(Mono.just(1)) }
        }
        assertEquals("42000", e.sqlState)
        val unique = assertFailsWith<R2dbcDataIntegrityViolationException> {
            withConnection<Int> { c ->
                Flux.from(c.createStatement("CREATE TEMPORARY TABLE u(a INT PRIMARY KEY); INSERT INTO u VALUES (1); INSERT INTO u VALUES (1)").execute())
                    .concatMap { it.rowsUpdated }.then(Mono.just(1))
            }
        }
        assertEquals(ru.ttraum.kotsql.ConstraintViolation.UNIQUE, unique.sqlErrorDetails()?.violation); assertEquals("PRIMARY", unique.sqlErrorDetails()?.constraint)
    }

    @Test fun springDatabaseClient() {
        val client = DatabaseClient.create(My.factory)
        client.sql("DROP TABLE IF EXISTS sp").then().block(Pg.timeout)
        client.sql("CREATE TABLE sp(id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(20))").then().block(Pg.timeout)
        assertEquals(1L, client.sql("INSERT INTO sp(name) VALUES (:name)").bind("name", "ada").fetch().rowsUpdated().block(Pg.timeout))
        assertEquals("ada", client.sql("SELECT name FROM sp WHERE name = :name").bind("name", "ada").map { row, _ -> row.get("name", String::class.java)!! }.one().block(Pg.timeout))
    }

    @Test fun connectionPoolUnderLoad() {
        val pool = ConnectionPool(ConnectionPoolConfiguration.builder(My.factory).maxSize(4).initialSize(1).validationQuery("SELECT 1").build())
        val sum = Flux.range(1, 300).flatMap({ i ->
            Mono.usingWhen(pool.create(), { c ->
                Flux.from(c.createStatement("SELECT $i").execute()).concatMap { r -> r.map { row, _ -> (row.get(0) as Number).toInt() } }.next()
            }) { Mono.from(it.close()) }
        }, 32).reduce(0, Int::plus).block(Pg.timeout)
        assertEquals(45150, sum)
        pool.dispose()
    }
}
